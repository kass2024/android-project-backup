fun appCopy(code: String): AppCopy = when (code) {
    "sw", "rw" -> swahili
    "fr" -> french
    else -> english
}

fun relationLabel(copy: AppCopy, code: String): String = when (code) {
    "father" -> copy.father
    "mother" -> copy.mother
    "guardian" -> copy.guardian
    "parent" -> copy.parentRole
    else -> ""
}

